// dsh-git-tree — build the browser half.
//
//   src/client/index.tsx  →  client.js (repo root, like dsh-file-finder)
//
// The output is the browser artifact format the Harness module loader serves:
// a CJS bundle wrapped in `window.__ModuleLoader__.load({ id, factory })`,
// where the factory's `require` is the frozen browser module table (react and
// the other baseline modules). This mirrors the official client bundle format
// and the build used by the installed reference plugin
// (/Users/chz/.dsh/local-plugins/dsh-workbench/build.mjs) — including the fact
// that the host half (`index.js`) is plain ESM and needs no build step.
//
// esbuild is resolved from, in order:
//   1. this skeleton's own node_modules        (npm i -D esbuild)
//   2. the installed dsh-workbench plugin      (already has esbuild 0.28.x)
// If neither exists the build stops with the exact remedy.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const log = (message) => console.log('[dsh-git-tree] ' + message)

// ── esbuild resolution ──────────────────────────────────────────────────────
const WORKBENCH_ESBUILD = '/Users/chz/.dsh/local-plugins/dsh-workbench/node_modules/esbuild/lib/main.js'
const CANDIDATES = [join(root, 'node_modules', 'esbuild', 'lib', 'main.js'), WORKBENCH_ESBUILD]

async function loadEsbuild() {
  try {
    return await import('esbuild')
  } catch {
    /* not installed locally */
  }
  for (const candidate of CANDIDATES) {
    try {
      const loaded = await import(pathToFileURL(candidate).href)
      if (typeof loaded.build === 'function') {
        log('using esbuild from ' + candidate)
        return loaded
      }
    } catch {
      /* try the next candidate */
    }
  }
  throw new Error(
    'esbuild not found. Fix one of:\n' +
      '  cd ' + root + ' && npm install --no-save esbuild\n' +
      '  — or install the reference plugin that ships esbuild at ' + WORKBENCH_ESBUILD,
  )
}

const { build } = await loadEsbuild()

// ── client half → client.js ─────────────────────────────────────────────────
const OUT_DIR = root
const TMP_BUNDLE = join(root, '.client.bundle.cjs')
mkdirSync(OUT_DIR, { recursive: true })

await build({
  entryPoints: [join(root, 'src', 'client', 'index.tsx')],
  outfile: TMP_BUNDLE,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  // Classic JSX transform onto React.createElement: the module only ever asks
  // the module table for `react`, so no `react/jsx-runtime` external is needed.
  jsx: 'transform',
  jsxFactory: 'h',
  jsxFragment: 'React.Fragment',
  // Resolved at runtime from the loader's frozen module table, never bundled.
  external: ['react'],
  legalComments: 'none',
  logLevel: 'info',
})

const body = readFileSync(TMP_BUNDLE, 'utf8')
rmSync(TMP_BUNDLE)

const wrapped = [
  '// Generated by build.mjs from src/client/index.tsx — do not edit directly.',
  'window.__ModuleLoader__.load({ id: "dsh-git-tree", factory: (require) => {',
  'var module = { exports: {} };',
  'var exports = module.exports;',
  body,
  'return module.exports;',
  '} });',
  '',
].join('\n')

writeFileSync(join(OUT_DIR, 'client.js'), wrapped)
log('wrote client.js (' + String(Buffer.byteLength(wrapped)) + ' bytes)')
