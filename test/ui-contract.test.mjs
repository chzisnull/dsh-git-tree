// Browser-artifact contract for the built client bundle.
//
// The browser half cannot be executed outside the Harness (it needs the
// module-loader facade and the live slot registry), so this test pins the
// shape that the app depends on: the loader wrapper, the slot ids the panel
// pairs, the routes it calls, and the rule that every colour is a theme token.

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const source = readFileSync(join(root, 'client.js'), 'utf8')

test('bundle is a Harness module-loader factory named after the package', () => {
  assert.match(source, /^\/\/ Generated by build\.mjs/)
  assert.match(source, /window\.__ModuleLoader__\.load\(\{ id: "dsh-git-tree", factory: \(require\) => \{/)
  assert.match(source, /return module\.exports;/)
})

test('React comes from the frozen module table and nothing else is required', () => {
  const requires = [...source.matchAll(/require\("([^"]+)"\)/g)].map((match) => match[1])
  assert.deepEqual([...new Set(requires)], ['react'])
})

test('panel pairs sidebar.panellist with the main keyed slot under one id', () => {
  assert.ok(source.includes('sidebar.panellist'), 'sidebar launcher must be registered')
  assert.ok(source.includes('"main"'), 'main panel must be registered')
  assert.ok(source.includes('"git-tree"'), 'both registrations must share the panel id')
  assert.equal(source.match(/slots\.inject\(/g)?.length, 2, 'exactly two slot injections')
  assert.equal(source.match(/slots\.register\(/g)?.length, 2, 'exactly two slot registrations')
})

test('client calls the host routes the plugin registers', () => {
  assert.ok(source.includes('api/git-tree/status'))
  assert.ok(source.includes('api/git-tree/diff'))
  assert.ok(source.includes('api/git-tree/open'), 'the local open action must call its route')
  assert.ok(source.includes('locale.register'), 'visible copy goes through the locale service')
})

test('local open buttons are gated to macOS and carry both copies', () => {
  assert.match(source, /['"]darwin['"]/, 'the toolbar must gate the local actions on darwin')
  for (const key of ['revealInFinder', 'openInTerminal', 'openFailed']) {
    assert.ok(source.includes(key), 'missing locale copy: ' + key)
  }
})

test('every colour is a --dsw-* theme token', () => {
  const tokens = new Set(source.match(/--dsw-[a-z0-9-]+/g) ?? [])
  assert.ok(tokens.size >= 12, 'expected the panel to lean on theme tokens, found ' + tokens.size)
  const hex = source.match(/#[0-9a-fA-F]{3,8}\b/g) ?? []
  assert.deepEqual(hex, [], 'no hardcoded hex colours may ship')
  const rgb = source.match(/\brgba?\(\s*\d/g) ?? []
  assert.deepEqual(rgb, [], 'no hardcoded rgb() colours may ship')
})

test('the artifact never rebuilds the page around the host', () => {
  assert.ok(!source.includes('document.body'), 'must not append a second application to document.body')
  assert.ok(!source.includes('innerHTML ='), 'must not replace host markup')
})
